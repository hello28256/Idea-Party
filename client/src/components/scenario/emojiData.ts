// 32 个常用 emoji 候选，按"场景创建"高频使用场景分类。
// 设计目标：让用户在 4x8 网格里能 1 次点击选中合适的图标，
// 避免让用户从系统 emoji 选择器里翻找（提升表单完成率）。
//
// 为什么不直接让用户输入：emoji 多字节序列容易复制出错（如 🎤 = U+1F3A4 + U+FE0F 变体选择符），
// 给定候选 + 自定义 Input 兜底是更可控的 UX。
//
// 扩展原则：保持每类 4 个，避免单类过多；总数 ≤ 40 时网格保持 5x8 一屏可见。
export const EMOJI_CANDIDATES: string[] = [
  // 职业类（4）
  '💼', '🤝', '💰', '📊',
  // 表达类（4）
  '💡', '🎯', '🚀', '⭐',
  // 学习类（4）
  '📚', '✍️', '🎓', '🧠',
  // 思考类（4）
  '🤔', '💭', '🔍', '🧐',
  // 创意类（4）
  '🎨', '✏️', '🖌️', '🎭',
  // 情感类（4）
  '❤️', '🌱', '🌟', '🔥',
  // 决策类（4）
  '⚖️', '🔀', '🧭', '🎲',
  // 沟通类（4）
  '💬', '🗣️', '📣', '👂'
]

/**
 * 检查字符串是否为合法 emoji 候选（命中列表或非空字符串）。
 * 真实 emoji 校验用 Intl.Segmenter 更准，但该 API 在 Safari 15.4+ 才支持，
 * 这里用「非空 + 长度 ≤ 8 字符」的宽松规则作为兜底（后端 VARCHAR(8) 也会兜底）。
 */
export function isValidEmoji(s: string): boolean {
  return s.length > 0 && s.length <= 8
}
